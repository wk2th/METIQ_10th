#!/usr/bin/env python3
"""Bake assets/metiq_logo.png into the two things the site needs from it.

1. core/src/logo_data.rs – the "METIQ" wordmark as 4-bit coverage, packed two
   pixels per byte, at the logo surface's native resolution. (The triangle
   mark is NOT baked: core/src/logo.rs draws it analytically from a traced
   polygon pair via signed distance fields.)
2. site/img/metiq_logo.gif – a 216-colour, ordered-dithered GIF that the page
   shows when JavaScript/WebAssembly is unavailable.

Usage: python3 tools/logo2rs.py   (requires Pillow)
"""
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "metiq_logo.png"
W, H = 240, 124
TEXT_BOX = (100, 316, 728, 392)  # wordmark region in source pixels


def coverage(img):
    """Luminance -> how much of each pixel is white lettering, 0..1."""
    lum = img.convert("L")
    return lum.point(lambda v: max(0, min(255, (v - 190) * 255 // 60)))


def bake_wordmark(src):
    sx = src.width / W
    sy = src.height / H
    x0, y0 = int(TEXT_BOX[0] / sx), int(TEXT_BOX[1] / sy)
    x1 = min(W, int(TEXT_BOX[2] / sx) + 1)
    y1 = min(H, int(TEXT_BOX[3] / sy) + 1)
    bw, bh = x1 - x0, y1 - y0
    crop = src.crop((x0 * sx, y0 * sy, x1 * sx, y1 * sy))
    cov = coverage(crop).resize((bw, bh), Image.Resampling.BOX)
    q = [min(15, (v + 8) // 17) for v in cov.tobytes()]
    if len(q) % 2:
        q.append(0)
    packed = bytes((q[i] << 4) | q[i + 1] for i in range(0, len(q), 2))

    rows = []
    for i in range(0, len(packed), 24):
        rows.append("    " + ", ".join(f"0x{b:02x}" for b in packed[i : i + 24]) + ",")
    body = "\n".join(rows)
    out = ROOT / "core" / "src" / "logo_data.rs"
    out.write_text(
        "// @generated by tools/logo2rs.py from assets/metiq_logo.png – do not edit.\n"
        "// METIQ wordmark, 4-bit coverage, high nibble first.\n\n"
        f"pub const WM_X: i32 = {x0};\n"
        f"pub const WM_Y: i32 = {y0};\n"
        f"pub const WM_W: i32 = {bw};\n"
        f"pub const WM_H: i32 = {bh};\n\n"
        "#[rustfmt::skip]\n"
        f"pub static WM: [u8; {len(packed)}] = [\n{body}\n];\n"
    )
    print(f"{out.relative_to(ROOT)}: {bw}x{bh} @ ({x0},{y0}), {len(packed)} bytes")


def bake_gif(src):
    small = src.convert("RGB").resize((W, H), Image.Resampling.LANCZOS)
    pal = Image.new("P", (1, 1))
    cube = [c for r in range(6) for g in range(6) for b in range(6) for c in (r * 51, g * 51, b * 51)]
    pal.putpalette(cube + [0] * (768 - len(cube)))
    gif = small.quantize(palette=pal, dither=Image.Dither.FLOYDSTEINBERG)
    out = ROOT / "site" / "img" / "metiq_logo.gif"
    gif.save(out, optimize=True)
    print(f"{out.relative_to(ROOT)}: {out.stat().st_size} bytes")


if __name__ == "__main__":
    src = Image.open(SRC)
    bake_wordmark(src)
    bake_gif(src)
