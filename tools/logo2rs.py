#!/usr/bin/env python3
"""Bake the METIQ wordmark out of assets/metiq_logo.png into core/src/logo_data.rs.

Only *shape* is taken from the artwork – the background it was exported on is
discarded. The triangle mark is not baked at all (core/src/logo.rs draws it
from traced polygons); the wordmark is, as 4-bit coverage packed two pixels
per byte, because it is set in a typeface we cannot ship.

This file is also the single source of truth for how source-artwork pixels map
onto the logo surface, so the composition is centred on the artwork's own
axis (x = 414.6, the triangle's apex) rather than on the old export's canvas.

Usage: python3 tools/logo2rs.py   (requires Pillow)
"""
import math
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "metiq_logo.png"

W, H = 240, 104          # surface size
S = 3.2                  # source px per surface px
AXIS = 414.6             # apex x in source = horizontal centre of the logo
TOP = 76.5               # apex y in source
SHADOW = 2               # drop-shadow offset (surface px), right & down
SX0 = AXIS - (W / 2 - SHADOW / 2) * S   # centre the mark+shadow pair
SY0 = TOP - 3 * S                        # 3px headroom above the apex
TEXT_BOX = (100, 316, 728, 392)          # wordmark region in source px


def bake_wordmark(src):
    bx0 = math.floor((TEXT_BOX[0] - SX0) / S)
    by0 = math.floor((TEXT_BOX[1] - SY0) / S)
    bx1 = min(W, math.ceil((TEXT_BOX[2] - SX0) / S))
    by1 = min(H, math.ceil((TEXT_BOX[3] - SY0) / S))
    bw, bh = bx1 - bx0, by1 - by0
    box = (bx0 * S + SX0, by0 * S + SY0, bx1 * S + SX0, by1 * S + SY0)
    # white lettering -> coverage, independent of whatever it sat on
    cov = src.convert("L").point(lambda v: max(0, min(255, (v - 190) * 255 // 60)))
    cov = cov.resize((bw, bh), Image.Resampling.BOX, box=box)
    q = [min(15, (v + 8) // 17) for v in cov.tobytes()]
    if len(q) % 2:
        q.append(0)
    packed = bytes((q[i] << 4) | q[i + 1] for i in range(0, len(q), 2))
    rows = "\n".join(
        "    " + ", ".join(f"0x{b:02x}" for b in packed[i : i + 24]) + ","
        for i in range(0, len(packed), 24)
    )
    out = ROOT / "core" / "src" / "logo_data.rs"
    out.write_text(
        "// @generated by tools/logo2rs.py from assets/metiq_logo.png – do not edit.\n\n"
        "// Surface geometry: source = (surface + 0.5) * S + (SX0, SY0)\n"
        f"pub const W: usize = {W};\n"
        f"pub const H: usize = {H};\n"
        f"pub const S: f32 = {S};\n"
        f"pub const SX0: f32 = {SX0!r};\n"
        f"pub const SY0: f32 = {SY0!r};\n"
        f"pub const AXIS: f32 = {AXIS};\n"
        f"pub const SHADOW: i32 = {SHADOW};\n\n"
        "// Wordmark, 4-bit coverage, high nibble first.\n"
        f"pub const WM_X: i32 = {bx0};\n"
        f"pub const WM_Y: i32 = {by0};\n"
        f"pub const WM_W: i32 = {bw};\n"
        f"pub const WM_H: i32 = {bh};\n\n"
        "#[rustfmt::skip]\n"
        f"pub static WM: [u8; {len(packed)}] = [\n{rows}\n];\n"
    )
    print(f"{out.relative_to(ROOT)}: wordmark {bw}x{bh} @ ({bx0},{by0}), {len(packed)} bytes")


if __name__ == "__main__":
    bake_wordmark(Image.open(SRC))
