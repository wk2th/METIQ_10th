#[rustfmt::skip]
const PUNCT: [(u8, [u8; 7]); 6] = [
    (b'!', [0b00100, 0b00100, 0b00100, 0b00100, 0b00100, 0b00000, 0b00100]),
    (b'-', [0b00000, 0b00000, 0b00000, 0b11111, 0b00000, 0b00000, 0b00000]),
    (b'.', [0b00000, 0b00000, 0b00000, 0b00000, 0b00000, 0b01100, 0b01100]),
    (b':', [0b00000, 0b01100, 0b01100, 0b00000, 0b01100, 0b01100, 0b00000]),
    (b'/', [0b00001, 0b00001, 0b00010, 0b00100, 0b01000, 0b10000, 0b10000]),
    (b'*', [0b00000, 0b00100, 0b10101, 0b01110, 0b10101, 0b00100, 0b00000]),
];

const BLANK: [u8; 7] = [0; 7];

pub fn glyph(c: u8) -> &'static [u8; 7] {
    match c {
        b'0'..=b'9' => &DIGITS[(c - b'0') as usize],
        b'A'..=b'Z' => &ALPHA[(c - b'A') as usize],
        b'a'..=b'z' => &ALPHA[(c - b'a') as usize],
        _ => {
            for (k, g) in PUNCT.iter() {
                if *k == c {
                    return g;
                }
            }
            &BLANK
        }
    }
}

/// Is pixel (`px`,`py`) – relative to the text origin – lit, for `text`
/// rendered at integer `scale` with 1 column of tracking?
#[inline]
pub fn mask(text: &[u8], scale: i32, px: i32, py: i32) -> bool {
    if px < 0 || py < 0 {
        return false;
    }
    let cell = 6 * scale;
    let ci = (px / cell) as usize;
    if ci >= text.len() {
        return false;
    }
    let col = (px % cell) / scale;
    let row = py / scale;
    if col >= 5 || row >= 7 {
        return false;
    }
    (glyph(text[ci])[row as usize] >> (4 - col)) & 1 == 1
}

/// Same, for a single digit glyph.
#[inline]
pub fn digit_mask(d: u32, scale: i32, px: i32, py: i32) -> bool {
    if px < 0 || py < 0 {
        return false;
    }
    let col = px / scale;
    let row = py / scale;
    if col >= 5 || row >= 7 {
        return false;
    }
    (DIGITS[(d % 10) as usize][row as usize] >> (4 - col)) & 1 == 1
}

pub const fn width(len: usize, scale: i32) -> i32 {
    len as i32 * 6 * scale - scale
}
